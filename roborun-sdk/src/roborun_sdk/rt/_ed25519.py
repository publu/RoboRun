"""Pure-python Ed25519 (RFC 8032 section 6 reference algorithm). Fallback only.

Used when neither ``cryptography`` nor ``PyNaCl`` is importable. It is correct but slow: a few milliseconds per verify
instead of 57-85 us. Segments arrive at 0.2-1 Hz and are verified once at acceptance, so this is acceptable as a
fallback; install ``roborun-sdk[crypto]`` for production. Not constant-time: signing here is for tests and the dev tools
only, never for device keys.
"""
